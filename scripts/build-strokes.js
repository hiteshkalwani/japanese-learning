// Run: node scripts/build-strokes.js — rebuilds kanji/strokes.js from KanjiVG for every kanji in kanji/*.js.
// Run it again after adding a kanji level.
const fs = require('fs');
const dir = `${__dirname}/../kanji`;
const TAG = 'r20260714'; // pinned KanjiVG release, so rebuilds are reproducible
global.window = {};
fs.readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'strokes.js').forEach(f => require(`${dir}/${f}`));
const chars = window.KANJI.flatMap(lv => lv.kanji.map(([char]) => char));

(async () => {
  const strokes = {};
  await Promise.all(chars.map(async char => {
    const hex = char.codePointAt(0).toString(16).padStart(5, '0');
    const res = await fetch(`https://raw.githubusercontent.com/KanjiVG/kanjivg/${TAG}/kanji/${hex}.svg`);
    if (!res.ok) throw new Error(`${char} (${hex}): HTTP ${res.status}`);
    // Stroke paths have ids like kvg:065e5-s1 and appear in stroke order.
    strokes[char] = [...(await res.text()).matchAll(/<path id="kvg:[^"]*-s\d+"[^>]* d="([^"]+)"/g)].map(m => m[1]);
    if (!strokes[char].length) throw new Error(`${char}: no strokes found`);
  }));
  const body = chars.map(c => `  '${c}': ${JSON.stringify(strokes[c])},`).join('\n');
  fs.writeFileSync(`${dir}/strokes.js`, `// Generated by scripts/build-strokes.js — do not edit by hand.
// Stroke order data from KanjiVG (https://kanjivg.tagaini.net), © Ulrich Apel,
// licensed under CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/). This file is shared under the same license.
// char -> SVG path per stroke, in stroke order, on a 109×109 viewBox.
window.STROKES = {
${body}
};
`);
  console.log(`Wrote ${chars.length} kanji to kanji/strokes.js`);
})().catch(e => { console.error(e.message); process.exit(1); });
